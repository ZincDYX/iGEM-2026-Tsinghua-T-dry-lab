import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import {rename,commitImport,ready} from '../local-web/helpers';

test('actual server kernels retain E1 selection in its file document and export exactly one current trajectory',async({page,context})=>{
  test.setTimeout(120000);
  const packagePath=process.env.FUSIONLAB_PS_V3_PACKAGE;
  test.skip(!packagePath,'Actual corrected synthetic package was not supplied; no substituted biological evidence.');
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');await ready(page);
  await page.getByText('File',{exact:true}).click();await page.getByRole('menuitem',{name:'New project',exact:true}).click();
  await rename(page,'PS-v3 object-bound acceptance');
  await page.getByLabel('Import data file').setInputFiles(packagePath!);await commitImport(page);
  await page.getByRole('button',{name:'Create demonstration plan',exact:true}).click();
  await expect(page.getByRole('button',{name:'Accept changes',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Accept changes',exact:true}).click();
  await page.getByRole('tab',{name:'Workflow',exact:true}).click();
  await expect(page.getByRole('button',{name:'Run',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Run',exact:true}).click();
  await expect(page.getByRole('button',{name:'Module Synthetic M3/M4 reference scenarios',exact:true})).toContainText('Completed',{timeout:90000});
  await page.getByRole('tab',{name:'Results',exact:true}).click();
  await expect(page.getByLabel('Result object',{exact:true})).toHaveCount(0);
  await page.getByLabel('Synthetic scenario').selectOption('E1');
  await expect(page.locator('.js-plotly-plot')).toBeVisible({timeout:20000});
  await expect(page.getByLabel('Species',{exact:true})).toHaveValue('15');
  await page.getByLabel('Phase',{exact:true}).selectOption('dilute');
  const quantity=await page.getByLabel('Quantity',{exact:true}).inputValue();
  const runId=await page.getByLabel('Run version').inputValue();
  const source=(await (await context.request.get('/api/platform/runs/'+runId+'/nodes/synthetic-demo/result')).json()).node.output;
  const expectedFile=source.cases.E1.trajectory_artifact.slice(6);
  await page.getByRole('button',{name:'Data',exact:true}).click();
  await expect(page.getByRole('tab',{name:'E1 time course',exact:true})).toHaveAttribute('aria-selected','true');
  await expect(page.getByRole('heading',{name:'E1 time course',exact:true})).toBeVisible();
  await expect(page.getByLabel('Species',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Phase',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Open file').getByText('Compound 15 concentration — dilute — concentration (uM)',{exact:true})).toBeVisible();
  const requests:string[]=[];page.on('request',request=>requests.push(request.url()));
  await page.getByRole('button',{name:'Close E1 time course',exact:true}).click();
  await expect(page.getByRole('tab',{name:'Results',exact:true})).toHaveAttribute('aria-selected','true');
  await expect(page.getByLabel('Synthetic scenario')).toHaveValue('E1');
  await expect(page.getByLabel('Phase',{exact:true})).toHaveValue('dilute');
  await expect(page.getByLabel('Quantity',{exact:true})).toHaveValue(quantity);
  await page.getByRole('button',{name:'Export',exact:true}).click();
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Recorded time course CSV',exact:true}).click()]);
  const csv=fs.readFileSync((await download.path())!,'utf8');
  expect(csv).toContain('Synthetic demo; not experimental validation');
  expect(csv).toContain('Compound 15');expect(csv.trim().split('\n')).toHaveLength(50);
  expect(requests.some(url=>url.includes('/files/'+expectedFile+'/series.csv'))).toBe(true);
  await page.getByLabel('Synthetic scenario').selectOption('E3');
  await expect(page.getByRole('heading',{name:'E3 · blocked · synthetic',exact:true})).toBeVisible();
  await expect(page.locator('.js-plotly-plot')).toHaveCount(0);
  expect(errors).toEqual([]);
});
