import {rename} from '../local-web/helpers';
import {test,expect} from '@playwright/test';

test('owned server executes reviewed scalar version and renders frozen unvalidated result',async({page,context})=>{
  // This connected suite is run against an authorized server acceptance
  // workspace, never a workstation calculator or a real user project.
  await page.goto('/');
  await expect(page.getByRole('tab',{name:'Inputs',exact:true})).toBeVisible();
  await page.getByText('File',{exact:true}).click();
  await page.getByRole('menuitem',{name:'New project',exact:true}).click();
  const name='Custom formula server acceptance '+Date.now();
  await rename(page,name);
  await page.getByText('File',{exact:true}).click();
  await page.getByRole('menuitem',{name:'Save',exact:true}).click();
  await expect(page.locator('.workbench-footer')).not.toContainText('Unsaved');
  const projects=await (await context.request.get('/api/platform/projects')).json();
  const project=projects.find((p:{name:string})=>p.name===name);
  expect(project).toBeTruthy();
  const method=(await (await context.request.get('/api/platform/methods')).json()).find((m:{id:string})=>m.id==='m3-s1-e10');
    const saved=await page.evaluate(async({project,method})=>{
      const response=await fetch(`/api/platform/projects/${project.id}/method-drafts`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({base_method_id:method.id,base_version:method.version,formula_id:'E1',title:'Server scalar ratio',latex:'x/(k+x)',reason:'Independent synthetic mathematical oracle, not biological evidence',source_reference:'Exact half ratio with SI conversion',expected_project_revision:project.revision,execution_spec:{expression:'x/(k+x)',output_unit:'1',variables:{x:{value:500,unit:'nM',source:'Synthetic analytic oracle'},k:{value:.5,unit:'uM',source:'Synthetic analytic oracle'}}}})});
      const draft=await response.json();
      const prepared=await fetch(`/api/platform/projects/${project.id}/method-drafts/${draft.id}/workflow`,{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'});
      const workflow=await prepared.json();
      const doc=await fetch(`/api/platform/projects/${project.id}/workflow-documents/formula-display`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({expected_project_revision:project.revision,workflow})});
      return {status:doc.status,text:await doc.text()};
    },{project,method});
  expect(saved.status,saved.text).toBe(200);

  await page.getByRole('tab',{name:'Workflow',exact:true}).click();
  await page.getByLabel('Open saved workflow').selectOption('formula-display');
  const graph=page.getByLabel('Workflow graph',{exact:true}),panel=page.getByLabel('Module method',{exact:true});
  await expect(graph.getByRole('button',{name:'Module Server scalar ratio',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Review changes',exact:true}).click();
  await page.getByRole('button',{name:'Accept changes',exact:true}).click();
  await page.getByRole('button',{name:'Run',exact:true}).click();
  await expect(graph.getByRole('button',{name:'Module Server scalar ratio',exact:true})).toContainText('Completed');
  await page.getByRole('tab',{name:'Results',exact:true}).click();
  await expect(page.getByLabel('Result object',{exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Custom formula result')).toContainText('0.5 1');
  const oldRun=await page.getByLabel('Run version').inputValue();
  await page.getByRole('tab',{name:'Workflow',exact:true}).click();
  await page.getByRole('button',{name:'Edit as new run',exact:true}).click();
  await expect(page.getByLabel('Current project',{exact:true})).not.toHaveValue(project.id);
  const iterationId=await page.getByLabel('Current project',{exact:true}).inputValue();
  const versions=async()=> (await (await context.request.get('/api/platform/projects/'+iterationId+'/method-drafts')).json()).items;
  await expect(panel.getByRole('button',{name:'Edit k',exact:true})).toHaveText('0.5');
  expect(await panel.getByRole('button',{name:'Edit x',exact:true}).count()).toBe(2);
  const before=(await versions()).length;
  await panel.getByRole('button',{name:'Edit k',exact:true}).click();await panel.getByLabel('Value for k').press('Enter');
  expect((await versions()).length).toBe(before);
  await panel.getByRole('button',{name:'Edit k',exact:true}).click();await panel.getByLabel('Value for k').fill('1.5');await panel.getByLabel('Value for k').press('Escape');
  expect((await versions()).length).toBe(before);
  await panel.getByRole('button',{name:'Edit k',exact:true}).click();await panel.getByLabel('Value for k').fill('1.5');await panel.getByLabel('Value for k').press('Enter');
  await expect(panel.getByRole('button',{name:'Edit k',exact:true})).toHaveText('1.5');
  expect((await versions()).length).toBe(before+1);
  await page.reload();await page.getByRole('tab',{name:'Workflow',exact:true}).click();
  await expect(panel.getByRole('button',{name:'Edit k',exact:true})).toHaveText('1.5');
  await page.getByRole('button',{name:'Review changes',exact:true}).click();await page.getByRole('button',{name:'Accept changes',exact:true}).click();await page.getByRole('button',{name:'Run',exact:true}).click();
  await expect(graph.getByRole('button',{name:'Module Server scalar ratio',exact:true})).toContainText('Completed');
  await page.getByRole('tab',{name:'Results',exact:true}).click();await expect(page.getByLabel('Custom formula result')).toContainText('0.25 1');
  const newRun=await page.getByLabel('Run version').inputValue();
  const fresh=await (await context.request.get('/api/platform/runs/'+newRun+'/nodes/formula/result')).json();
  const old=await (await context.request.get('/api/platform/runs/'+oldRun+'/nodes/formula/result')).json();
  expect(fresh.node.output.value).toBe(.25);expect(old.node.output.value).toBe(.5);
  expect(fresh.node.output.method.spec.variables.k.value).toBe(1.5);expect(old.node.output.method.spec.variables.k.value).toBe(.5);
  expect(fresh.node.output.method.method_version).toBe(2);expect(old.node.output.method.method_version).toBe(1);
  await page.getByLabel('Current project',{exact:true}).selectOption(project.id);
  await page.getByRole('tab',{name:'Results',exact:true}).click();await page.getByLabel('Run version').selectOption(oldRun);
  await expect(page.getByLabel('Custom formula result')).toContainText('0.5 1');
  await page.getByRole('tab',{name:'Workflow',exact:true}).click();
  await expect(panel.getByRole('button',{name:'Edit k',exact:true})).toHaveCount(0);
  await expect(panel.getByLabel('Formula input values')).toContainText('0.5');
});
