"""Method metadata/original-source transcription; never calls a solver."""
import ast
from pathlib import Path
from fastapi.testclient import TestClient
from workbench_fixture import fixture_app
from igem_drylab.workflow.methods import METHODS


def test_all_original_steps_and_equations_are_retained_without_approximation_rewrite():
    assert {step.id for step in METHODS['m1-v3'].steps} == {str(i) for i in range(6)}
    assert {step.id for step in METHODS['m2-v2'].steps} == {'L1','L2','L3','Q1','Q2','Q3','Q4'}
    assert {step.id for step in METHODS['m3-s1-e10'].steps} == {f'S{i}' for i in range(1,6)} | {f'E{i}' for i in range(1,11)}
    assert {step.id for step in METHODS['m4-step0-step8'].steps} == {str(i) for i in range(9)}
    formulas = {f.id:f for f in METHODS['m3-s1-e10'].formulas}
    # Literal original equations, not generated by the scientific calculators.
    assert formulas['E2'].latex == r'c_{OC}^{tot}=\Phi[x+\theta_{SH3}n_{SH3}^{eff}c_{dense}]+(1-\Phi)\frac{x}{K_{OC}}'
    assert formulas['E7'].status == 'conditional' and r'\approx' not in formulas['E7'].latex
    assert formulas['capacity'].status == 'source_discrepancy'
    assert {f.id for f in METHODS['m4-step0-step8'].formulas if f.id.startswith('balance-')} == {f'balance-{i}' for i in range(8,16)}
    assert all(not m.formal_formula_editable and m.symbols and m.source_version for m in METHODS.values())


def test_registry_links_resolve_to_existing_python_modules_or_functions_without_importing_them():
    source = Path(__file__).resolve().parents[1]/'src'
    for method in METHODS.values():
        assert (source.parent/method.source_reference).is_file()
        for formula in method.formulas:
            for reference in formula.implementation:
                parts = reference.split('.')
                module = source.joinpath(*parts).with_suffix('.py')
                if module.is_file(): continue
                module = source.joinpath(*parts[:-1]).with_suffix('.py')
                assert module.is_file(),reference
                assert any(isinstance(node,(ast.FunctionDef,ast.ClassDef)) and node.name == parts[-1]
                    for node in ast.parse(module.read_text(encoding='utf-8')).body),reference


def test_actual_module_method_api_is_read_only_and_does_not_claim_real_tool_job(tmp_path):
    app = fixture_app(tmp_path)
    with TestClient(app) as client:
        response = client.get('/api/platform/projects/software-fixture/module-method?tool_id=project.m3')
        assert response.status_code == 200,response.text
        value = response.json()
        assert value['tool']['status'] == 'registered_not_tested'
        assert value['methods'][0]['id'] == 'm3-s1-e10'
        assert app.state.platform_store.runs() == [] and app.state.fixture_calls == []
        assert client.get('/api/platform/projects/not-owned/module-method?tool_id=project.m3').status_code == 404


def test_frozen_module_parameters_use_actual_snapshot_not_live_draft(tmp_path):
    from test_parameter_review_service import seed
    from igem_drylab.workflow.builtins import recommend
    app=fixture_app(tmp_path)
    project,_=seed(app)
    workflow=recommend(project,'scientific_pipeline')
    run=app.state.workflow_engine.create(project,workflow)
    project.scientific_project['config']['parameters'][0]['value']=.9
    app.state.platform_store.save_project(project,project.revision)
    with TestClient(app) as client:
        response=client.get(f'/api/platform/projects/software-fixture/module-method?tool_id=project.m1&run_id={run}')
        assert response.status_code==200,response.text
        assert response.json()['parameter_records'][0]['value']==.2
        assert response.json()['project_revision']==project.revision
        assert client.get('/api/platform/projects/software-fixture/module-method?tool_id=project.m3').json()['parameter_records'][0]['value']==.9
        assert app.state.fixture_calls==[]
