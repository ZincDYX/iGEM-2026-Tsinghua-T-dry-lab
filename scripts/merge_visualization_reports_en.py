# -*- coding: utf-8 -*-
from __future__ import annotations

import re
from pathlib import Path

import fulltext_pro_field_completion as ft


ROOT = ft.ROOT
ESSAY = ROOT / "essay"
ATLAS = ESSAY / "known_information_visualization_report_en.html"
SHOWCASE = ESSAY / "project_showcase_extended_figures_en.html"
OUT = ESSAY / "combined_project_visualization_report_en.html"


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="ignore")


def extract_style(doc: str) -> str:
    match = re.search(r"<style>(.*?)</style>", doc, flags=re.S | re.I)
    return match.group(1).strip() if match else ""


def extract_main(doc: str) -> str:
    match = re.search(r"<main>(.*?)</main>", doc, flags=re.S | re.I)
    if match:
        return match.group(1).strip()
    body = re.search(r"<body[^>]*>(.*?)</body>", doc, flags=re.S | re.I)
    return body.group(1).strip() if body else doc


def strip_hero_and_footer(fragment: str) -> str:
    fragment = re.sub(r"\s*<section class=\"hero\">.*?</section>\s*", "\n", fragment, count=1, flags=re.S | re.I)
    fragment = re.sub(r"\s*<footer>.*?</footer>\s*", "\n", fragment, flags=re.S | re.I)
    return fragment.strip()


def build() -> str:
    atlas_doc = read(ATLAS)
    showcase_doc = read(SHOWCASE)
    atlas_style = extract_style(atlas_doc)
    showcase_style = extract_style(showcase_doc)
    atlas_main = strip_hero_and_footer(extract_main(atlas_doc))
    showcase_main = strip_hero_and_footer(extract_main(showcase_doc))

    combined_style = f"""
{atlas_style}

/* Supplemental styles from the project-showcase report. */
{showcase_style}

/* Combined-report layout overrides. */
main {{
  width: min(1240px, calc(100% - 32px));
  margin: 0 auto;
  padding: 32px 0 54px;
}}
.report-nav {{
  display: flex;
  flex-wrap: wrap;
  gap: 10px;
  margin-top: 22px;
}}
.report-nav a {{
  display: inline-block;
  color: #2f6fbb;
  text-decoration: none;
  border: 1px solid var(--line);
  background: #ffffff;
  border-radius: 999px;
  padding: 8px 12px;
  font-size: 14px;
  font-weight: 700;
}}
.chapter {{
  margin-top: 28px;
  padding: 22px 26px;
  border-radius: 14px;
  background: #111827;
  color: #ffffff;
}}
.chapter .eyebrow {{
  color: #93c5fd;
}}
.chapter h2 {{
  margin: 0;
  color: #ffffff;
  font-size: 28px;
}}
.chapter p {{
  max-width: 960px;
  margin: 10px 0 0;
  color: #d1d5db;
  line-height: 1.55;
}}
.combined-footer {{
  color: var(--muted);
  line-height: 1.55;
  margin-top: 24px;
}}
@media print {{
  body {{ background: #ffffff; }}
  .panel, .stat, .hero {{ box-shadow: none; }}
  .report-nav {{ display: none; }}
}}
"""

    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Combined iGEM Literature Database Visualization Report</title>
<style>
{combined_style}
</style>
</head>
<body>
<main>
<section class="hero">
  <p class="eyebrow">Integrated project visualization report</p>
  <h1>iGEM Literature-Derived Experimental Database</h1>
  <p class="lead">This combined English report merges the known-information atlas with project-showcase figures. It emphasizes recognized records, traceable evidence chains, condition distributions, titer benchmarks, enzyme-parameter landscapes, and LLPS-related design signals.</p>
  <div class="report-nav">
    <a href="#database-atlas">Database Atlas</a>
    <a href="#project-showcase">Project Showcase Figures</a>
  </div>
</section>

<section id="database-atlas" class="chapter">
  <p class="eyebrow">Part I</p>
  <h2>Known Information Atlas</h2>
  <p>Overview figures for recognized product, host, evidence, and graph relationships after cleaning, LLM quality control, and full-text or supplementary-material completion.</p>
</section>
{atlas_main}

<section id="project-showcase" class="chapter">
  <p class="eyebrow">Part II</p>
  <h2>Project Showcase Figures</h2>
  <p>Presentation-oriented figures for product-family concentration, host dominance, reaction-condition reference ranges, titer benchmarks, enzyme parameters, and LLPS regulatory evidence.</p>
</section>
{showcase_main}

<footer class="combined-footer">
  <p>Generated by merging <code>known_information_visualization_report_en.html</code> and <code>project_showcase_extended_figures_en.html</code>. Source data are retained in the full-text-completed literature extraction database.</p>
</footer>
</main>
</body>
</html>
"""


def main() -> None:
    OUT.write_text(build(), encoding="utf-8")
    print(f"Wrote: {OUT}")


if __name__ == "__main__":
    main()
